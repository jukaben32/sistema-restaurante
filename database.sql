-- Tablas para restaurante: mesas, pedidos y items de pedido
CREATE TABLE IF NOT EXISTS mesas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20) NOT NULL UNIQUE,
    descripcion VARCHAR(100),
    estado VARCHAR(20) DEFAULT 'libre' CHECK (estado IN ('libre','ocupada','reservada','bloqueada')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pedidos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesa_id INT NOT NULL REFERENCES mesas(id),
    cliente_id INT REFERENCES clientes(id),
    -- Nombre del usuario que abrió la comanda (snapshot para trazabilidad)
    mesero_nombre VARCHAR(100) NULL,
    estado VARCHAR(20) DEFAULT 'abierto'
        CHECK (estado IN ('abierto','en_cocina','preparando','listo','servido','cerrado','cancelado','rechazado')),
    total NUMERIC(10,2) NOT NULL DEFAULT 0,
    notas TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pedido_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INT NOT NULL REFERENCES pedidos(id),
    producto_id INT NOT NULL REFERENCES productos(id),
    cantidad NUMERIC(10,2) NOT NULL,
    unidad_medida VARCHAR(5) DEFAULT 'UND' CHECK (unidad_medida IN ('KG','UND','LB')),
    precio_unitario NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,
    -- Estado del item (lo que cocina procesa). "rechazado" se usa para visualizar cancelaciones.
    estado VARCHAR(20) DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente','enviado','preparando','listo','servido','cancelado','rechazado')),
    nota TEXT NULL,
    enviado_at TIMESTAMPTZ NULL,
    preparado_at TIMESTAMPTZ NULL,
    listo_at TIMESTAMPTZ NULL,
    servido_at TIMESTAMPTZ NULL,
    -- Cuándo la línea se incluyó en una comanda impresa (evita duplicar impresión)
    comanda_impresa_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

