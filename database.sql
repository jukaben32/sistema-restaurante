-- Mantiene updated_at al día (equivalente a ON UPDATE CURRENT_TIMESTAMP de MySQL)
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS productos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    precio_kg NUMERIC(10,2) NOT NULL DEFAULT 0,
    precio_unidad NUMERIC(10,2) NOT NULL DEFAULT 0,
    precio_libra NUMERIC(10,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Relación padre -> hijo usando productos existentes (legado/compatibilidad)
-- Relacionado con:
-- - routes/productos.js (endpoints /api/productos/:padreId/hijos)
-- - public/js/mesas.js (fallback cuando no hay hijos-items)
CREATE TABLE IF NOT EXISTS producto_hijos (
    producto_padre_id INT NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
    producto_hijo_id INT NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (producto_padre_id, producto_hijo_id)
);

-- Hijos como "items" de texto (NO son productos, no tienen precio)
-- Ejemplo: Producto padre "CORRIENTE" -> items: "Goulash de cerdo", "Crema"
-- Relacionado con:
-- - routes/productos.js (endpoints /api/productos/:padreId/hijos-items)
-- - views/productos.ejs + public/js/productos.js (panel para administrar items)
-- - public/js/mesas.js (al montar pedido: seleccionar items y guardar en pedido_items.nota)
CREATE TABLE IF NOT EXISTS producto_hijos_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_padre_id INT NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
    nombre VARCHAR(120) NOT NULL,
    orden INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_padre_nombre UNIQUE (producto_padre_id, nombre)
);

CREATE TABLE IF NOT EXISTS clientes (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    direccion TEXT,
    telefono VARCHAR(20),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS facturas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INT REFERENCES clientes(id),
    fecha TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    total NUMERIC(10,2) NOT NULL,
    -- forma_pago se mantiene por compatibilidad (reportes/ventas); si hay varios pagos se guarda 'mixto'
    forma_pago VARCHAR(20) NOT NULL DEFAULT 'efectivo'
        CHECK (forma_pago IN ('efectivo','transferencia','tarjeta','qr','mixto'))
);

-- Pagos por factura (pago mixto: varias filas por la misma factura)
-- Relacionado con:
-- - routes/facturas.js (POST /api/facturas)
-- - routes/mesas.js (POST /api/mesas/pedidos/:id/facturar)
-- - views/factura.ejs (imprime el detalle de pagos)
CREATE TABLE IF NOT EXISTS factura_pagos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id INT NOT NULL REFERENCES facturas(id) ON DELETE CASCADE,
    metodo VARCHAR(20) NOT NULL CHECK (metodo IN ('efectivo','transferencia','tarjeta','qr')),
    monto NUMERIC(10,2) NOT NULL,
    referencia VARCHAR(100) NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS detalle_factura (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id INT REFERENCES facturas(id),
    producto_id INT REFERENCES productos(id),
    cantidad NUMERIC(10,2) NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
    unidad_medida VARCHAR(5) DEFAULT 'KG' CHECK (unidad_medida IN ('KG','UND','LB')),
    subtotal NUMERIC(10,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS configuracion_impresion (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_negocio VARCHAR(100) NOT NULL,
    direccion TEXT,
    telefono VARCHAR(20),
