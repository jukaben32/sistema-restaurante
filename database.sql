-- Cada cobro con Stripe (Checkout Session). Se marca "usado" al quedar en una factura,
-- así un mismo pago no se puede aplicar dos veces.
CREATE TABLE IF NOT EXISTS stripe_pagos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(255) NOT NULL UNIQUE,
    pedido_id INT REFERENCES pedidos(id) ON DELETE SET NULL,
    monto NUMERIC(12,2) NOT NULL,
    moneda VARCHAR(3) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente','pagado','expirado','usado')),
    payment_intent VARCHAR(255),
    url TEXT,
    factura_id INT REFERENCES facturas(id) ON DELETE SET NULL,
    creado_por VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Avisos que el cliente envía desde el menú QR (llamar mesero, pedir cuenta, pedido nuevo)
CREATE TABLE IF NOT EXISTS mesa_alertas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesa_id INT NOT NULL REFERENCES mesas(id) ON DELETE CASCADE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('llamar_mesero','pedir_cuenta','nuevo_pedido')),
    mensaje TEXT,
    atendida SMALLINT NOT NULL DEFAULT 0,
    atendida_por VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    atendida_at TIMESTAMPTZ
);

-- Reservas (internas y desde la web pública /reservar)
CREATE TABLE IF NOT EXISTS reservas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(30),
    email VARCHAR(120),
    personas INT NOT NULL DEFAULT 2 CHECK (personas > 0),
    fecha_hora TIMESTAMPTZ NOT NULL,
    mesa_id INT REFERENCES mesas(id) ON DELETE SET NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente','confirmada','sentada','completada','cancelada','no_show')),
    origen VARCHAR(20) NOT NULL DEFAULT 'interno' CHECK (origen IN ('interno','web')),
    notas TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Inventario: insumos, recetas (insumos por producto) y movimientos
CREATE TABLE IF NOT EXISTS insumos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    unidad VARCHAR(20) NOT NULL DEFAULT 'und',
    stock NUMERIC(12,3) NOT NULL DEFAULT 0,
    stock_minimo NUMERIC(12,3) NOT NULL DEFAULT 0,
    costo_unitario NUMERIC(12,2) NOT NULL DEFAULT 0,
    activo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS recetas (
    producto_id INT NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
    insumo_id INT NOT NULL REFERENCES insumos(id) ON DELETE CASCADE,
    cantidad NUMERIC(12,3) NOT NULL CHECK (cantidad > 0),
    PRIMARY KEY (producto_id, insumo_id)
);

CREATE TABLE IF NOT EXISTS inventario_movimientos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insumo_id INT NOT NULL REFERENCES insumos(id) ON DELETE CASCADE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('entrada','salida','ajuste','venta')),
    cantidad NUMERIC(12,3) NOT NULL,
    stock_resultante NUMERIC(12,3),
    factura_id INT REFERENCES facturas(id) ON DELETE SET NULL,
    nota TEXT,
    usuario VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

